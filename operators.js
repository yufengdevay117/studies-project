/**
 * OPERATORS:
 * 
 * 0: (introduction)
 * Operators are symbols used to perform operations on values and variables. JavaScript 
 * uses different categories of operators to assign values, perform math calculations, 
 * compare values, or combine logical conditions.
 * 
 * 1. Assignment operators are used to assign values to variables (like `=`).
 * 
 * 2. Arithmetic operators are used to perform mathematical calculations (like `+`, `-`, `*`, `/`).
 * 
 * 3. Comparison operators compare two values and return a boolean flag (`true` or `false`).
 * 
 * 4. Logical operators combine multiple boolean expressions together (like `&&` and `||`).
 */

// 1. Assignment Operators //
let x = 10; // assigns the value 10 to x
console.log(x); // prints => 10

// 2. Arithmetic Operators //
let sum = 5 + 3; // adds 5 and 3
console.log(sum); // prints => 8

// 3. Comparison Operators //
let isEqual = (5 === 5); // checks if values and types are strictly equal
console.log(isEqual); // prints => true

// 4. Logical Operators //
let hasAccess = (true && false); // returns true only if BOTH sides are true
console.log(hasAccess); // prints => false