/**
 * DATATYPES:
 * 
 * 0: (introduction)
 * Data types define the type of data a variable can hold. In JavaScript, there are 
 * Primitive types (like numbers, strings, and booleans) which hold a single simple value, 
 * and Complex types (like arrays and objects) which hold collections of data.
 * 
 * 1. Numbers represent numeric values used for math.
 * 
 * 2. Strings represent text wrapped in quotes.
 * 
 * 3. Booleans represent true or false flags.
 */

// 1. Numbers //
let age = 25;
console.log(age); // prints => 25

// 2. Strings //
let name = "Alex";
console.log(name); // prints => Alex

// 3. Booleans //
let isStudent = true;
console.log(isStudent); // prints => true