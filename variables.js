/**
 * VARIABLES:
 * 
 * 0: (introduction)
 * Variables are named containers used to store data values in computer memory during the life 
 * cycle of a program. They act as identifiers that point to values of various types, allowing us 
 * to reference and manipulate information dynamically throughout our code.
 * 
 * 1. Declaration creates a variable by defining its name using a keyword (`var`, `let`, or `const`).
 * 
 * 2. Assignment initializes or updates a variable by storing a value inside it using the `=` operator.
 * 
 * 3. Reassignment changes the existing value stored in a variable to a new value.
 */

// 1. Declaration //
let standardPrice;
console.log(standardPrice); // prints => undefined

// 2. Assignment //
standardPrice = 100;
console.log(standardPrice); // prints => 100

// 3. Reassignment //
standardPrice = 150;
console.log(standardPrice); // prints => 150